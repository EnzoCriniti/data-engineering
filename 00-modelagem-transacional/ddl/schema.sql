CREATE TABLE IF NOT EXISTS cliente (
    cliente_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome         VARCHAR(100)  NOT NULL,
    cidade       VARCHAR(100)  NOT NULL,
    email        VARCHAR(150)  NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS categoria (
    categoria_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome         VARCHAR(80)   NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS produto (
    produto_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome         VARCHAR(120)  NOT NULL,
    preco        NUMERIC(10,2) NOT NULL CHECK (preco > 0),
    categoria_id INTEGER       NOT NULL REFERENCES categoria(categoria_id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS entregador (
    entregador_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(100) NOT NULL,
    veiculo       VARCHAR(40)  NOT NULL CHECK (veiculo IN ('moto','van','bicicleta'))
);

CREATE TABLE IF NOT EXISTS pedido (
    pedido_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id  INTEGER      NOT NULL REFERENCES cliente(cliente_id) ON DELETE RESTRICT,
    data_pedido TIMESTAMP    NOT NULL DEFAULT now(),
    status      VARCHAR(20)  NOT NULL CHECK (status IN ('pendente','pago','cancelado')) DEFAULT 'pendente'
);

CREATE TABLE IF NOT EXISTS item_pedido (
    item_pedido_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id      INTEGER      NOT NULL REFERENCES pedido(pedido_id) ON DELETE CASCADE,
    produto_id     INTEGER      NOT NULL REFERENCES produto(produto_id) ON DELETE RESTRICT,
    quantidade     INTEGER      NOT NULL CHECK (quantidade > 0),
    preco_unitario NUMERIC(10,2) NOT NULL CHECK (preco_unitario > 0),
    UNIQUE (pedido_id, produto_id)
);

CREATE TABLE IF NOT EXISTS pagamento (
    pagamento_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       INTEGER       NOT NULL REFERENCES pedido(pedido_id) ON DELETE CASCADE,
    valor           NUMERIC(12,2) NOT NULL CHECK (valor > 0),
    metodo          VARCHAR(40)   NOT NULL CHECK (metodo IN ('pix','cartao_credito','cartao_debito','boleto')),
    status          VARCHAR(20)   NOT NULL CHECK (status IN ('pendente','pago','recusado')) DEFAULT 'pendente',
    data_pagamento  TIMESTAMP     NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS entrega (
    entrega_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id     INTEGER      NOT NULL REFERENCES pedido(pedido_id) ON DELETE CASCADE,
    entregador_id INTEGER      NOT NULL REFERENCES entregador(entregador_id) ON DELETE RESTRICT,
    status        VARCHAR(20)  NOT NULL CHECK (status IN ('em_transito','entregue','devolvido')) DEFAULT 'em_transito',
    data_saida    TIMESTAMP    NOT NULL DEFAULT now(),
    data_entrega  TIMESTAMP,
    UNIQUE (pedido_id)
);
